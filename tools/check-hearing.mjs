const seen=new Set();
for(let i=0;i<100;i++){
  const task=createHearingTask('HEARING-'+i);assert.deepEqual(task,createHearingTask('HEARING-'+i));seen.add(task.patient.name);
  assert(!handInHearing(task));assert(!chooseHearingGrade(task,'b230.1'));assert.equal(checkHearingInputs(task),'missing');
  assert(!setHearingValue(task,'right',0,52));assert(!setHearingValue(task,'middle',0,50));
  for(const ear of ['right','left'])for(let index=0;index<4;index++)assert(setHearingValue(task,ear,index,0));
  assert.equal(checkHearingInputs(task),'mismatch');assert.equal(task.result,null);
  for(const ear of ['right','left'])for(let index=0;index<4;index++)assert(setHearingValue(task,ear,index,task.patient[ear][index]));
  assert.equal(checkHearingInputs(task),'ok');assert.equal(task.stage,'diagnosis');
  const resumed=JSON.parse(JSON.stringify(task));assert(!handInHearing(resumed));assert(!chooseHearingGrade(resumed,'b230.9'));
  assert(chooseHearingGrade(resumed,resumed.result.grade));assert.equal(resumed.stage,'handoff');assert(handInHearing(resumed));assert(!handInHearing(resumed));assert(!setHearingValue(resumed,'left',0,50));
}
