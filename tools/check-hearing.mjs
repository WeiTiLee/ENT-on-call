import assert from 'node:assert/strict';
import {HEARING_PATIENTS,HEARING_FREQUENCIES,calculateHearing,createHearingTask,setHearingValue,checkHearingInputs,chooseHearingGrade,handInHearing,audiogramSVG} from '../dist/game/hearing-game.js';
